'use client';

import { useState } from 'react';
import { useRouter } from 'next/navigation';
import { motion } from 'framer-motion';
import { useWorkout } from '@/hooks/use-workout';
import type { Exercise } from '@/types';
import { ArrowLeft, ChevronRight, Loader2, Zap, Dumbbell, Target, Flame, Layers } from 'lucide-react';
import { cn } from '@/lib/utils';

// Workout template data with icons
const workoutTemplates = [
  {
    id: 'push',
    name: 'Push Day',
    description: 'Pecho, Hombros, Triceps',
    icon: Target,
    exercises: ['Bench Press', 'Overhead Press', 'Incline Dumbbell Press', 'Tricep Dips', 'Lateral Raises'],
    color: 'from-orange-500/10 to-red-500/10',
  },
  {
    id: 'pull',
    name: 'Pull Day',
    description: 'Espalda, Biceps',
    icon: Layers,
    exercises: ['Pull-ups', 'Barbell Rows', 'Lat Pulldowns', 'Bicep Curls', 'Face Pulls'],
    color: 'from-blue-500/10 to-cyan-500/10',
  },
  {
    id: 'legs',
    name: 'Leg Day',
    description: 'Piernas, Gluteos',
    icon: Flame,
    exercises: ['Squats', 'Deadlifts', 'Lunges', 'Leg Press', 'Calf Raises'],
    color: 'from-green-500/10 to-emerald-500/10',
  },
  {
    id: 'upper',
    name: 'Upper Body',
    description: 'Tren superior completo',
    icon: Dumbbell,
    exercises: ['Bench Press', 'Pull-ups', 'Overhead Press', 'Rows', 'Dips'],
    color: 'from-purple-500/10 to-pink-500/10',
  },
  {
    id: 'full',
    name: 'Full Body',
    description: 'Entrenamiento completo',
    icon: Zap,
    exercises: ['Squats', 'Bench Press', 'Deadlifts', 'Pull-ups', 'Overhead Press'],
    color: 'from-amber-500/10 to-yellow-500/10',
  },
];

export default function NewWorkoutPage() {
  const router = useRouter();
  const { startWorkout } = useWorkout();
  const [loadingId, setLoadingId] = useState<string | null>(null);

  const handleStartWorkout = async (templateId: string | null) => {
    setLoadingId(templateId || 'quick-start');
    try {
      const template = templateId
        ? workoutTemplates.find((t) => t.id === templateId)
        : null;

      const now = new Date();
      const autoGeneratedName = `Entrenamiento ${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')} ${String(now.getHours()).padStart(2, '0')}:${String(now.getMinutes()).padStart(2, '0')}`;

      const exercises: Exercise[] = template
        ? template.exercises.map((exerciseName, index) => ({
            id: `exercise-${Date.now()}-${index}`,
            sessionId: '',
            name: exerciseName,
            sets: [],
            restTime: 60,
            order: index,
            createdAt: now.toISOString(),
            updatedAt: now.toISOString(),
          }))
        : [];

      const workout = await startWorkout({
        name: autoGeneratedName,
        exercises,
      });

      if (workout) {
        router.push(`/workout/active`);
      }
    } catch (error) {
      console.error('Error creating workout:', error);
      alert('Error al crear el entrenamiento. Por favor, intenta de nuevo.');
      setLoadingId(null);
    }
  };

  return (
    <div className="min-h-screen bg-background text-foreground">
      {/* Background elements */}
      <div className="absolute inset-0 grid-pattern opacity-30 pointer-events-none" />
      <div className="absolute top-0 right-0 h-96 w-96 rounded-full bg-accent/5 blur-[120px] pointer-events-none" />

      <div className="relative z-10 max-w-2xl mx-auto px-6 py-8">
        {/* Header */}
        <motion.div
          initial={{ opacity: 0, y: -10 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ duration: 0.3 }}
          className="flex items-center gap-4 mb-10"
        >
          <button
            onClick={() => router.back()}
            className="flex items-center justify-center h-10 w-10 rounded-full border border-border bg-card transition-colors hover:bg-secondary hover:border-muted-foreground/30"
            aria-label="Volver"
          >
            <ArrowLeft className="h-5 w-5 text-muted-foreground" />
          </button>
          <div>
            <p className="text-sm text-muted-foreground">Crear</p>
            <h1 className="text-2xl font-semibold tracking-tight">Nuevo entrenamiento</h1>
          </div>
        </motion.div>

        {/* Quick Start Section */}
        <motion.div
          initial={{ opacity: 0, y: 20 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ duration: 0.4, delay: 0.1 }}
          className="mb-12"
        >
          <button
            onClick={() => handleStartWorkout(null)}
            disabled={loadingId !== null}
            className="group relative w-full overflow-hidden rounded-2xl border border-border bg-card p-8 transition-all duration-300 hover:border-accent/50 hover:shadow-lg hover:shadow-accent/5"
          >
            <div className="absolute inset-0 bg-gradient-to-br from-accent/10 via-transparent to-transparent opacity-0 group-hover:opacity-100 transition-opacity duration-300" />
            <div className="relative flex items-center justify-between">
              <div className="flex items-center gap-4">
                <div className="flex h-14 w-14 items-center justify-center rounded-xl bg-foreground text-background">
                  {loadingId === 'quick-start' ? (
                    <Loader2 className="h-6 w-6 animate-spin" />
                  ) : (
                    <Zap className="h-6 w-6" />
                  )}
                </div>
                <div className="text-left">
                  <h2 className="text-xl font-semibold">Inicio rapido</h2>
                  <p className="text-sm text-muted-foreground">
                    Comienza un entrenamiento vacio
                  </p>
                </div>
              </div>
              <ChevronRight className="h-6 w-6 text-muted-foreground transition-transform group-hover:translate-x-1 group-hover:text-foreground" />
            </div>
          </button>
        </motion.div>

        {/* Templates Section */}
        <motion.div
          initial={{ opacity: 0, y: 20 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ duration: 0.4, delay: 0.2 }}
        >
          <div className="flex items-center justify-between mb-6">
            <h2 className="text-sm font-medium text-muted-foreground uppercase tracking-wider">
              Rutinas predefinidas
            </h2>
            <div className="h-px flex-1 ml-4 bg-gradient-to-r from-border to-transparent" />
          </div>

          <div className="space-y-3">
            {workoutTemplates.map((template, index) => {
              const Icon = template.icon;
              return (
                <motion.button
                  key={template.id}
                  initial={{ opacity: 0, x: -20 }}
                  animate={{ opacity: 1, x: 0 }}
                  transition={{ duration: 0.3, delay: 0.3 + index * 0.05 }}
                  onClick={() => handleStartWorkout(template.id)}
                  disabled={loadingId !== null}
                  className={cn(
                    'group relative w-full overflow-hidden rounded-xl border border-border bg-card p-5 text-left transition-all duration-300',
                    'hover:border-accent/30 hover:shadow-md',
                    loadingId === template.id && 'border-accent/50'
                  )}
                >
                  <div
                    className={cn(
                      'absolute inset-0 bg-gradient-to-br opacity-0 group-hover:opacity-100 transition-opacity duration-300',
                      template.color
                    )}
                  />
                  <div className="relative flex items-center justify-between">
                    <div className="flex items-center gap-4">
                      <div className="flex h-11 w-11 items-center justify-center rounded-lg bg-secondary group-hover:bg-secondary/80 transition-colors">
                        <Icon className="h-5 w-5 text-foreground" />
                      </div>
                      <div>
                        <h3 className="font-medium text-foreground group-hover:text-foreground/90 transition-colors">
                          {template.name}
                        </h3>
                        <p className="text-xs text-muted-foreground">
                          {template.description} · {template.exercises.length} ejercicios
                        </p>
                      </div>
                    </div>

                    <div className="flex items-center gap-2 text-muted-foreground">
                      {loadingId === template.id ? (
                        <Loader2 className="h-5 w-5 animate-spin text-accent" />
                      ) : (
                        <ChevronRight className="h-5 w-5 transition-transform group-hover:translate-x-1 group-hover:text-foreground" />
                      )}
                    </div>
                  </div>
                </motion.button>
              );
            })}
          </div>
        </motion.div>

        {/* Bottom info */}
        <motion.div
          initial={{ opacity: 0 }}
          animate={{ opacity: 1 }}
          transition={{ duration: 0.4, delay: 0.6 }}
          className="mt-12 text-center"
        >
          <p className="text-xs text-muted-foreground">
            Puedes modificar los ejercicios durante tu entrenamiento
          </p>
        </motion.div>
      </div>
    </div>
  );
}
